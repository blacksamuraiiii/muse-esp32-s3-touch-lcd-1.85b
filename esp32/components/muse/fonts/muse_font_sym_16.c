/* Fork note (2026-11-03): the symbol tail of the Noto chain. Noto Sans SC
 * Medium covers CJK + fullwidth only, Montserrat 16 covers ASCII + the
 * private-use LVGL icons, and neither has the Latin-1 symbols, degree-C/F,
 * quotes, arrows or geometric shapes the UI prints (weather 25℃, hints,
 * reply text). Those 30 glyphs live here, cut from DejaVu Sans 16 px 4bpp
 * with lv_font_conv@1.5.3, the same tool and shape as upstream's faces:
 *   npx lv_font_conv@1.5.3 --font DejaVuSans.ttf --size 16 --bpp 4 \
 *     --format lvgl --lv-font-name muse_font_sym_16 --no-compress \
 *     -r 0x00A0 -r 0x00A7 -r 0x00B0 -r 0x00B1 -r 0x00B5 -r 0x00B7 \
 *     -r 0x00D7 -r 0x00F7 -r 0x2013-0x2015 -r 0x2018-0x201D -r 0x2026 \
 *     -r 0x2039-0x203A -r 0x2103 -r 0x2109 -r 0x2116 -r 0x2190-0x2193 \
 *     -r 0x25B6 -r 0x25CB -r 0x25CF
 * The ranges are spelled out glyph by glyph on purpose: the first cut took
 * the whole 0x2000-0x205F block, which pulled in the invisible format
 * characters (U+200B-U+200F, U+202A-U+202E, U+2028/9). lv_font_conv writes
 * each code point into a comment, and GCC 15's -Werror=bidi-chars then
 * refuses the file. None of those characters can be drawn, so leaving them
 * out is the fix, not escaping the comments.
 * The face is a fallback only, so its own line metrics never govern a
 * layout - but 21/5 keeps a symbol's baseline level with Noto's 20/5. */


